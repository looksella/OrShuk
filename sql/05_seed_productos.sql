-- ------------------------------------------------------------
-- Inventario inicial
-- ------------------------------------------------------------
-- Se carga usando la funcion transaccional, asi cada producto
-- queda con su movimiento de INVENTARIO_INICIAL en el libro.
DO $$
DECLARE
  r RECORD;
BEGIN
  FOR r IN
    SELECT p.id AS pid, p.tenant_id AS tid, b.id AS bid,
           GREATEST(p.min_stock * 3, 10)::NUMERIC(14,3) AS qty,
           p.cost_price AS cost
    FROM products p
    JOIN branches b ON b.tenant_id = p.tenant_id
    WHERE p.track_stock
  LOOP
    IF NOT EXISTS (
      SELECT 1 FROM stock_movements
      WHERE product_id = r.pid AND branch_id = r.bid
        AND movement_type = 'INVENTARIO_INICIAL'
    ) THEN
      PERFORM fn_mover_stock(
        r.tid, r.bid, r.pid, 'INVENTARIO_INICIAL',
        r.qty, r.cost, 'CARGA_INICIAL', NULL,
        'Inventario inicial de la semilla', NULL
      );
    END IF;
  END LOOP;
END $$;

COMMIT;

