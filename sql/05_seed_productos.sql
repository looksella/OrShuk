\echo ''
\echo '=== Productos por empresa ==='
SELECT t.name AS empresa,
       COUNT(DISTINCT c.id) AS categorias,
       COUNT(p.id)          AS productos
FROM tenants t
LEFT JOIN categories c ON c.tenant_id = t.id
LEFT JOIN products   p ON p.tenant_id = t.id
GROUP BY t.name
ORDER BY t.name;

\echo ''
\echo '=== Valor del inventario ==='
SELECT t.name AS empresa,
       SUM(sb.quantity * p.cost_price)::NUMERIC(12,2) AS valor_costo,
       SUM(sb.quantity * p.sale_price)::NUMERIC(12,2) AS valor_venta
FROM stock_balances sb
JOIN products p ON p.id = sb.product_id
JOIN tenants  t ON t.id = sb.tenant_id
GROUP BY t.name
ORDER BY t.name;

